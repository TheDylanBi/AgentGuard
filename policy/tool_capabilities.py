DEFAULT_CAPABILITY = _caps([])


def build_tool_caps(tools):
    """Return {tool: capability} from the static registry (default fallback)."""
    per = {}
    for t in sorted(tools):
        entry = TOOL_CAPABILITIES.get(t)
        if entry is not None:
            caps = dict(entry)
            caps["actions"] = [t]
            per[t] = caps
        else:
            caps = dict(DEFAULT_CAPABILITY)
            caps["actions"] = [t]
            per[t] = caps
    return per
